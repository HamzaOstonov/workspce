package com.is.openwayj.model;

public class SubProduct {

	private String code_prod_way;
	private String code_subprod_way;
	private String name_subprod_way;
	private String name_subprod_ibs;
	
	public String getCode_prod_way() {
		return code_prod_way;
	}
	public void setCode_prod_way(String code_prod_way) {
		this.code_prod_way = code_prod_way;
	}
	public String getCode_subprod_way() {
		return code_subprod_way;
	}
	public void setCode_subprod_way(String code_subprod_way) {
		this.code_subprod_way = code_subprod_way;
	}
	public String getName_subprod_way() {
		return name_subprod_way;
	}
	public void setName_subprod_way(String name_subprod_way) {
		this.name_subprod_way = name_subprod_way;
	}
	public String getName_subprod_ibs() {
		return name_subprod_ibs;
	}
	public void setName_subprod_ibs(String name_subprod_ibs) {
		this.name_subprod_ibs = name_subprod_ibs;
	}
	
}
